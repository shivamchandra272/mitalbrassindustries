function cycleProductImage(img, productName, direction = 1) {
    if (!img) return;
    const gallery = (img.dataset.gallery || "")
        .split('|')
        .map(value => value.trim())
        .filter(Boolean);

    if (gallery.length <= 1) return;

    let currentIndex = parseInt(img.dataset.index || "0", 10);
    const nextIndex = (currentIndex + direction + gallery.length) % gallery.length;
    img.dataset.index = nextIndex;
    img.src = gallery[nextIndex];
    img.alt = productName;

    const counter = img.parentElement ? img.parentElement.querySelector('.gallery-counter') : null;
    if (counter) {
        counter.textContent = `${nextIndex + 1}/${gallery.length}`;
    }
}

