function displayProducts() {

    const searchText =
        search.value.toLowerCase();

    const selectedCategory =
        categoryFilter.value;


    const filteredProducts =
        products.filter(product => {

            const matchesSearch =
                product.name
                    .toLowerCase()
                    .includes(searchText);

            const matchesCategory =
                selectedCategory === "" ||
                product.category === selectedCategory;

            return matchesSearch && matchesCategory;

        });


    productGrid.innerHTML = "";


    if (filteredProducts.length === 0) {

        productGrid.innerHTML = `
            <p>
                No products found.
            </p>
        `;

        return;
    }


    filteredProducts.forEach(product => {
        const productIndex = products.indexOf(product);

        const card =
            document.createElement("article");

        card.className =
            "product-card";

        const gallery = Array.isArray(product.gallery) && product.gallery.length
            ? product.gallery
            : (product.image ? [product.image] : []);

        function getImageUrl(item) {
            if (!item) return createProductImage(product.name, product.category);
            if (item.startsWith("http://") || item.startsWith("https://") || item.startsWith("data:") || item.startsWith("images/") || item.startsWith("Mobile Devices/")) {
                return item;
            }
            return `Mobile Devices/${item}.jpg`;
        }

        const imageSrc = gallery.length ? getImageUrl(gallery[0]) : createProductImage(product.name, product.category);
        const galleryUrls = gallery.map(getImageUrl);

        const hasMultiple = galleryUrls.length > 1;

        card.innerHTML = `
            <div class="product-image">
                <img src="${escapeHTML(imageSrc)}" alt="${escapeHTML(product.name)}" loading="lazy" data-gallery="${escapeHTML(galleryUrls.join('|'))}" data-index="0" data-product-index="${productIndex}" data-action="gallery-next">
                ${hasMultiple ? `
                    <button class="gallery-nav-btn gallery-prev" data-action="gallery-prev" data-product-index="${productIndex}" aria-label="Previous view">‹</button>
                    <button class="gallery-nav-btn gallery-next" data-action="gallery-next" data-product-index="${productIndex}" aria-label="Next view">›</button>
                    <span class="gallery-badge" title="Click or use arrows to view photos">📷 <span class="gallery-counter">1/${galleryUrls.length}</span></span>
                ` : ''}
                <div class="image-placeholder" hidden>MBI</div>
            </div>
            <div class="product-info">
                <span class="product-badge">${escapeHTML(product.category)}</span>
                <h3>${escapeHTML(product.name)}</h3>
                ${product.sizes ? `<div class="product-size-tag"><strong>Size:</strong> ${escapeHTML(product.sizes)}</div>` : ''}
                <p>${escapeHTML(product.description || "Precision component • Custom specifications available")}</p>
                <button class="btn small-btn" data-action="enquire" data-product-index="${productIndex}">Enquire</button>
            </div>
        `;

        const image = card.querySelector(".product-image img");
        image.addEventListener("error", () => {
            image.src = createProductImage(product.name, product.category);
            image.hidden = true;
            card.querySelector(".image-placeholder").hidden = false;
        }, { once: true });


        productGrid.appendChild(card);

    });

}

