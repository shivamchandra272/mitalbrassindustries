document
    .getElementById("enquiryForm")
    .addEventListener("submit", async function(event) {
        event.preventDefault();
        const form = event.currentTarget;
        const submitButton = form.querySelector('button[type="submit"]');
        submitButton.disabled = true;
        submitButton.textContent = "Sending...";
        try {
            const response = await fetch("api/index.php?action=enquiries", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    name: document.getElementById("name").value.trim(),
                    phone: document.getElementById("phone").value.trim(),
                    email: document.getElementById("email").value.trim(),
                    company: document.getElementById("company").value.trim(),
                    message: document.getElementById("message").value.trim(),
                    product: document.getElementById("productName").value
                })
            });
            const result = await response.json();
            if (!response.ok) throw new Error(result.error || "The enquiry could not be sent.");
            alert("Thank you. Your enquiry has been sent to Mital Brass Industries.");
            form.reset();
        } catch (error) {
            const message = window.location.protocol === "file:"
                ? "The enquiry form needs the PHP server. Open the website at http://127.0.0.1:8082/index.html and keep MySQL running in XAMPP."
                : error instanceof TypeError
                    ? "Could not reach the PHP backend. Make sure the PHP server and MySQL are running, then reopen the website at http://127.0.0.1:8082/index.html."
                    : error.message || "The enquiry could not be sent. Please try again or contact us by phone.";
            alert(message);
        } finally {
            submitButton.disabled = false;
            submitButton.textContent = "Send Enquiry";
        }
    });

async function loadDatabaseData() {
    try {
        const response = await fetch("api/index.php?action=products");
        if (response.ok) {
            const data = await response.json();
            if (Array.isArray(data.products) && data.products.length) {
                products = data.products;
                populateCategories();
                displayProducts();
            }
        }
    } catch {
        // Keep the bundled catalog available when opened without the PHP server.
    }

    try {
        const response = await fetch("api/index.php?action=settings");
        if (!response.ok) return;
        const { settings } = await response.json();
        if (!settings) return;
        if (settings.company_name) {
            document.getElementById("companyName").textContent = settings.company_name;
            document.getElementById("footerCompanyName").textContent = settings.company_name;
        }
        if (settings.phone) document.getElementById("companyPhone").textContent = settings.phone;
        if (settings.email) {
            const emailLink = document.getElementById("companyEmailLink");
            const contactEmail = document.getElementById("companyEmailContact");
            emailLink.href = `mailto:${settings.email}`;
            emailLink.textContent = `${settings.email} →`;
            contactEmail.href = `mailto:${settings.email}?subject=Product%20Enquiry`;
            contactEmail.textContent = `${settings.email} →`;
        }
        if (settings.city) {
            document.getElementById("companyTopLocation").textContent = `📍 ${settings.city}`;
            document.getElementById("companyLocation").textContent = settings.city;
        }
        if (settings.description) document.getElementById("companyDescription").textContent = settings.description;
        if (settings.whatsapp) {
            const number = settings.whatsapp.replace(/\D/g, "");
            document.getElementById("companyWhatsappLink").href = `https://wa.me/${number}`;
        }
    } catch {
        // Keep the published contact details if settings are unavailable.
    }
}


